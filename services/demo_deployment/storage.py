"""Generated benign-byte immutable provisioning check. Not an asset/model installer."""
import hashlib
import os
import stat
import tempfile

from tools.phase2e.demo_governance.artifacts import snapshot_fd
from tools.phase2e.owner_only_v3.records import require

BUFFER = b'Find Our Child private readiness probe; generated bytes; no photograph or model.\n'


def provision_probe(directory):
    fd = os.open(directory, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW)
    name = hashlib.sha256(BUFFER).hexdigest() + '.probe'
    temporary = '.probe-' + os.urandom(16).hex()
    output = None
    try:
        row = os.fstat(fd)
        require(row.st_uid == os.geteuid() and row.st_mode & 0o077 == 0, 'probe_private_directory')
        with tempfile.TemporaryFile() as source:
            source.write(BUFFER);source.flush()
            with snapshot_fd(source.fileno(), size=len(BUFFER), sha256=hashlib.sha256(BUFFER).hexdigest()) as sealed:
                output = os.open(temporary, os.O_CREAT | os.O_EXCL | os.O_WRONLY | os.O_NOFOLLOW, 0o600, dir_fd=fd)
                data = os.pread(sealed, len(BUFFER), 0)
                require(data == BUFFER, 'probe_sealed_bytes')
                view = memoryview(data)
                while view:
                    count = os.write(output, view);require(count > 0, 'probe_write');view = view[count:]
                os.fchmod(output, 0o400);os.fsync(output)
                # No replace: an existing entry, symlink or competing install is a failure.
                os.link(temporary, name, src_dir_fd=fd, dst_dir_fd=fd, follow_symlinks=False)
                os.unlink(temporary, dir_fd=fd);os.fsync(fd)
        read = os.open(name, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK, dir_fd=fd)
        try:
            row = os.fstat(read)
            require(stat.S_ISREG(row.st_mode) and row.st_nlink == 1 and row.st_mode & 0o222 == 0
                    and os.read(read, len(BUFFER) + 1) == BUFFER, 'probe_immutable_identity')
        finally:
            os.close(read)
        return {'generated_bytes': len(BUFFER), 'sha256': hashlib.sha256(BUFFER).hexdigest(),
                'kernel_sealed': True, 'no_replace': True, 'models': 0, 'images': 0}
    finally:
        if output is not None:
            os.close(output)
        try:
            os.unlink(temporary, dir_fd=fd)
        except FileNotFoundError:
            pass
        os.close(fd)
